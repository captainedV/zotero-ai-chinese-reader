	let locale = 'en-US';

	M.I18n = {
		init(prefLocale) {
			let candidate = prefLocale || 'en-US';
			if (!STRINGS[candidate]) {
				candidate = String(candidate).toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US';
			}
			locale = STRINGS[candidate] ? candidate : 'en-US';
		},
		get locale() {
			return locale;
		},
		/** Whether a key exists in the active dictionary (test helper). */
		has(key) {
			const dict = STRINGS[locale] || STRINGS['en-US'];
			return Object.prototype.hasOwnProperty.call(dict, key)
				|| Object.prototype.hasOwnProperty.call(STRINGS['en-US'], key);
		},
		/** All keys of the active dictionary (test helper). */
		keys() {
			const dict = STRINGS[locale] || STRINGS['en-US'];
			return Object.keys({ ...STRINGS['en-US'], ...dict });
		},
		/** Translate `key`, interpolating `{name}` placeholders from `vars`. */
		t(key, vars) {
			const dict = STRINGS[locale] || STRINGS['en-US'];
			let value = dict[key] ?? STRINGS['en-US'][key] ?? key;
			if (vars) {
				value = value.replace(/\{(\w+)\}/g, (m, name) => (vars[name] ?? m));
			}
			return value;
		}
	};
