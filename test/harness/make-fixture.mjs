/**
 * Generates test/harness/fixture.js from a real PDF using the plugin's own
 * layout engine, so the browser harness renders pixel-accurate pages.
 *
 * Usage: node test/harness/make-fixture.mjs [pdfPath] [maxPages]
 */
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import { loadPlugin, ROOT } from '../harness.mjs';

const HERE = path.dirname(url.fileURLToPath(import.meta.url));

const DEFAULT_PDF = '/Users/xia/Zotero/storage/VTII8MTH/Xiao 等 - Deterministic Image-to-Image Translation via Denoising Brownian Bridge Models with Dual Approximator.pdf';

const pdfPath = process.argv[2] && !process.argv[2].startsWith('-') ? process.argv[2] : DEFAULT_PDF;
const maxPages = Number(process.argv[3] || 3);

const pdfjs = await import(path.join('/tmp/pdfcheck/node_modules/pdfjs-dist/legacy/build/pdf.mjs'));
pdfjs.GlobalWorkerOptions.workerSrc = path.join('/tmp/pdfcheck/node_modules/pdfjs-dist/legacy/build/pdf.worker.mjs');

const M = loadPlugin('util.js', 'layout.js', 'sentences.js');

const data = new Uint8Array(fs.readFileSync(pdfPath));
const pdfDocument = await pdfjs.getDocument({
  data,
  standardFontDataUrl: path.join('/tmp/pdfcheck/node_modules/pdfjs-dist/standard_fonts/')
}).promise;

const meta = await pdfDocument.getMetadata().catch(() => ({ info: {} }));
const pages = [];
let paragraphIndex = 0;
const allParagraphs = [];

for (let i = 1; i <= Math.min(maxPages, pdfDocument.numPages); i++) {
  const page = await pdfDocument.getPage(i);
  const view = page.view;
  const textContent = await page.getTextContent();
  const built = M.Layout.buildPage(textContent.items, { view, rotation: page.rotate || 0 }, i - 1, {});
  built.pageIndex = i - 1;
  built.view = view;
  for (const paragraph of built.paragraphs) {
    paragraph.id = `p${paragraphIndex++}`;
    paragraph.pageIndex = i - 1;
    allParagraphs.push(paragraph);
  }
  pages.push(built);
}

const fullText = allParagraphs.map(p => p.text).join('\n\n');
const fixture = {
  attachmentKey: 'HARNESS0000',
  itemID: 1,
  numPages: pdfDocument.numPages,
  pages,
  paragraphs: allParagraphs.map(p => ({
    id: p.id,
    pageIndex: p.pageIndex,
    rects: p.rects,
    text: p.text,
    lines: p.lines.map(line => ({ rect: line.rect, text: line.text, items: line.items }))
  })),
  fullText,
  textLength: fullText.length,
  fingerprint: `harness-${allParagraphs.length}`,
  meta: {
    title: meta?.info?.Title || 'Deterministic Image-to-Image Translation via Denoising Brownian Bridge Models',
    authors: meta?.info?.Author || 'Tianren Xiao, Xinyuan Hu, Yutong Wang',
    venue: 'CVPR 2025',
    year: '2025',
    abstract: allParagraphs.find(p => /this paper|we propose/i.test(p.text))?.text?.slice(0, 900) || ''
  }
};

// Keep the fixture small enough to inline as a script.
const out = `/* generated by make-fixture.mjs — real geometry from ${path.basename(pdfPath)} */
window.MOONLIT_FIXTURE = ${JSON.stringify(fixture)};
`;
fs.writeFileSync(path.join(HERE, 'fixture.js'), out);
console.log(`fixture: ${pages.length} pages, ${allParagraphs.length} paragraphs, ${(out.length / 1024).toFixed(1)} KiB`);
